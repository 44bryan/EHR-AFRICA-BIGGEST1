class Command(BaseCommand):
    help = 'Seed standard laboratory test types (LOINC-aligned, WHO/Africa practice)'

    def add_arguments(self, parser):
        parser.add_argument('--update', action='store_true',
                            help='Update existing tests (default: skip existing)')

    def handle(self, *args, **options):
        update = options['update']
        created = 0
        updated = 0
        skipped = 0

        for t in LAB_TESTS:
            defaults = {
                'name': t['name'],
                'category': t['category'],
                'result_type': t.get('result_type', 'QUANTITATIVE'),
                'result_options': t.get('result_options', []),
                'normal_range': t.get('normal_range', {}),
                'sample_type': t.get('sample_type', ''),
                'turnaround_hours': t.get('turnaround_hours', 24),
                'description': t.get('description', ''),
                'is_active': True,
            }
            # Skip if a test with same name already exists under a different code
            existing_by_name = LabTestType.objects.filter(name=t['name']).exclude(code=t['code']).first()
            if existing_by_name:
                skipped += 1
                continue

            obj, was_created = LabTestType.objects.get_or_create(
                code=t['code'],
                defaults=defaults,
            )
            if was_created:
                created += 1
                self.stdout.write(f'  [+] {obj.code} — {obj.name}')
            elif update:
                for k, v in defaults.items():
                    setattr(obj, k, v)
                obj.save()
                updated += 1
                self.stdout.write(f'  [~] {obj.code} — {obj.name}')
            else:
                skipped += 1

        self.stdout.write(self.style.SUCCESS(
            f'\nDone: {created} created, {updated} updated, {skipped} skipped.'
        ))
        if skipped and not update:
            self.stdout.write('  Tip: run with --update to overwrite existing records.')
