for code, desc, is_oph in DIAGNOSES:
    obj, was_created = Diagnosis.objects.get_or_create(
        icd10_code=code,
        defaults={'description': desc, 'is_ophthalmic': is_oph, 'is_active': True},
    )
    if was_created:
        created += 1
    else:
        # Update description if it changed
        changed = False
        if obj.description != desc:
            obj.description = desc
            changed = True
        if obj.is_ophthalmic != is_oph:
            obj.is_ophthalmic = is_oph
            changed = True
        if not obj.is_active:
            obj.is_active = True
            changed = True
        if changed:
            obj.save()
            updated += 1
        else:
            skipped += 1

